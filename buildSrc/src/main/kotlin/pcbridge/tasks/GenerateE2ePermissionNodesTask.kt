package pcbridge.tasks

import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

/**
 * Locates all Kotlin objects constructing a [PermissionNode] then
 * generates a TypeScript file containing a constant for each one.
 * This allows us to reuse the same permission nodes in E2E tests
 * without duplicating the definitions by hand.
 */
abstract class GenerateE2ePermissionNodesTask : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val permissionSources: ConfigurableFileCollection

    @get:OutputFile
    abstract val outputFile: RegularFileProperty

    @TaskAction
    fun generate() {
        val constructorPattern = Regex("""\bPermissionNode\s*\(""")
        val classPattern = Regex("""\bclass\s+PermissionNode\s*\(""")
        val declarationPattern = Regex("""\bval\s+([A-Z][A-Z0-9_]*)\s*=\s*PermissionNode\s*\(\s*"([^"]+)"\s*\)""")
        val groups = sortedMapOf<String, MutableMap<String, String>>()

        permissionSources.files
            .sortedBy { it.path }
            .forEach { sourceFile ->
                val source = sourceFile.readText()
                val declarations = declarationPattern.findAll(source).toList()
                val constructors = constructorPattern.findAll(source).count() -
                    classPattern.findAll(source).count()
                if (declarations.size != constructors) {
                    throw GradleException(
                        "Could not generate permission nodes from $sourceFile. " +
                            "Declare each node as `val NAME = PermissionNode(\"literal.node\")`.",
                    )
                }

                if (declarations.isEmpty()) return@forEach

                val group = sourceFile.name.removeSuffix("Permissions.kt").toCamelCase()
                val permissions = groups.getOrPut(group) { sortedMapOf() }
                declarations.forEach { declaration ->
                    val name = declaration.groupValues[1].toCamelCase()
                    val node = declaration.groupValues[2]
                    if (permissions.put(name, node) != null) {
                        throw GradleException("Duplicate permission name `$group.$name`")
                    }
                }
            }

        val generatedSource =
            buildString {
                appendLine("// Generated by :app:paper-plugin:generateE2ePermissionNodes. Do not edit.")
                appendLine("export const permissionNodes = {")
                groups.forEach { (group, permissions) ->
                    appendLine("  $group: {")
                    permissions.forEach { (name, node) ->
                        val escapedNode = node.replace("\\", "\\\\").replace("'", "\\'")
                        appendLine("    $name: '$escapedNode',")
                    }
                    appendLine("  },")
                }
                appendLine("} as const;")
            }

        outputFile.get().asFile.apply {
            parentFile.mkdirs()
            writeText(generatedSource)
        }
    }

    private fun String.toCamelCase(): String = replace(Regex("([a-z0-9])([A-Z])"), "$1_$2")
        .split('_')
        .mapIndexed { index, part ->
            part.lowercase().replaceFirstChar {
                if (index == 0) it.lowercase() else it.uppercase()
            }
        }.joinToString("")
}
